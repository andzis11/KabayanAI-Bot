# ============================================
#  KABAYAN AGENT v3.0 — Setup Wizard (Windows)
# ============================================

$ErrorActionPreference = "Stop"

Write-Host ""
Write-Host "  ╔══════════════════════════════════════════════╗" -ForegroundColor Cyan
Write-Host "  ║                                              ║" -ForegroundColor Cyan
Write-Host "  ║      🍎 KABAYAN AGENT v3.0                  ║" -ForegroundColor Cyan
Write-Host "  ║      Setup Wizard                            ║" -ForegroundColor Cyan
Write-Host "  ║                                              ║" -ForegroundColor Cyan
Write-Host "  ║      AI Trading Bot On-Chain Solana          ║" -ForegroundColor Cyan
Write-Host "  ║      MEV Bot | AI Agent v2.0                 ║" -ForegroundColor Cyan
Write-Host "  ║                                              ║" -ForegroundColor Cyan
Write-Host "  ╚══════════════════════════════════════════════╝" -ForegroundColor Cyan
Write-Host ""

Write-Host "Step 1/6: Checking dependencies..." -ForegroundColor White
Write-Host ""

$missing = @()

try { $nodeVer = node -v; Write-Host "  ✓ Node.js $nodeVer" -ForegroundColor Green } catch { $missing += "Node.js v18+" }
try { $npmVer = npm -v; Write-Host "  ✓ npm $npmVer" -ForegroundColor Green } catch { $missing += "npm" }

if ($missing.Count -gt 0) {
    Write-Host ""
    Write-Host "  ✗ Missing: $($missing -join ', ')" -ForegroundColor Red
    Write-Host "  Install from: https://nodejs.org" -ForegroundColor Yellow
    exit 1
}

Write-Host ""
Write-Host "Step 2/6: Installing npm packages..." -ForegroundColor White
Write-Host ""

if (Test-Path "node_modules") {
    Write-Host "  ⚠ node_modules exists — reinstalling" -ForegroundColor Yellow
    Remove-Item -Recurse -Force node_modules
}

npm install
Write-Host "  ✓ Dependencies installed" -ForegroundColor Green
Write-Host ""

Write-Host "Step 3/6: Creating directories..." -ForegroundColor White
Write-Host ""

New-Item -ItemType Directory -Force -Path "data" | Out-Null
New-Item -ItemType Directory -Force -Path "logs" | Out-Null
New-Item -ItemType Directory -Force -Path "src/assets" | Out-Null

Write-Host "  ✓ data/" -ForegroundColor Green
Write-Host "  ✓ logs/" -ForegroundColor Green
Write-Host "  ✓ src/assets/" -ForegroundColor Green
Write-Host ""

Write-Host "Step 4/6: Configuration" -ForegroundColor White
Write-Host ""

$skipEnv = $false

if (Test-Path ".env") {
    $overwrite = Read-Host "  .env exists — overwrite? (y/N)"
    if ($overwrite -ne "y" -and $overwrite -ne "Y") {
        Write-Host "  ✓ Keeping existing .env" -ForegroundColor Green
        $skipEnv = $true
    }
}

if (-not $skipEnv) {
    Copy-Item ".env.example" ".env"

    Write-Host "  ── Telegram Bot ──" -ForegroundColor Cyan
    Write-Host "  1. Open @BotFather in Telegram"
    Write-Host "  2. Type /newbot"
    Write-Host "  3. Copy the bot token"
    Write-Host ""
    $tgToken = Read-Host "  Telegram Bot Token"

    Write-Host ""
    Write-Host "  ── Chat ID ──" -ForegroundColor Cyan
    Write-Host "  1. Open @userinfobot in Telegram"
    Write-Host "  2. Type /start"
    Write-Host "  3. Copy your ID"
    Write-Host ""
    $tgChat = Read-Host "  Telegram Chat ID"

    Write-Host ""
    Write-Host "  ── Solana Wallet ──" -ForegroundColor Cyan
    Write-Host "  ⚠ Use a DEDICATED trading wallet!" -ForegroundColor Yellow
    Write-Host ""
    $solKey = Read-Host "  Solana Private Key (Base58)"

    Write-Host ""
    Write-Host "  ── Helius API ──" -ForegroundColor Cyan
    Write-Host "  Sign up: https://dev.helius.xyz"
    Write-Host ""
    $heliusKey = Read-Host "  Helius API Key"

    Write-Host ""
    Write-Host "  ── AI Providers ──" -ForegroundColor Cyan
    Write-Host "  Groq (FREE): https://console.groq.com"
    $groqKey = Read-Host "  Groq API Key (Enter to skip)"

    Write-Host "  Anthropic: https://console.anthropic.com"
    $anthropicKey = Read-Host "  Anthropic API Key (Enter to skip)"

    Write-Host "  OpenAI: https://platform.openai.com"
    $openaiKey = Read-Host "  OpenAI API Key (Enter to skip)"

    Write-Host ""
    Write-Host "  ── Jito (MEV) ──" -ForegroundColor Cyan
    $jitoKey = Read-Host "  Jito API Key (Enter to skip)"

    Write-Host ""
    Write-Host "  ── Trading Settings ──" -ForegroundColor Cyan
    $dailyCap = Read-Host "  Daily Capital (SOL) [default: 1]"
    if (-not $dailyCap) { $dailyCap = "1" }

    $baseRisk = Read-Host "  Base Risk % [default: 2]"
    if (-not $baseRisk) { $baseRisk = "2" }

    @"
# ============================================
#  KABAYAN AGENT v3.0 — Environment Config
#  Generated by Setup Wizard
# ============================================

# === WAJIB ===
TELEGRAM_BOT_TOKEN=$tgToken
SOLANA_PRIVATE_KEY=$solKey
HELIUS_API_KEY=$heliusKey

# === TELEGRAM ===
CHAT_ID=$tgChat
BOT_USERNAME=KabayanBot
DAILY_REPORT_CHAT_ID=$tgChat

# === AI PROVIDERS ===
GROQ_API_KEY=$groqKey
ANTHROPIC_API_KEY=$anthropicKey
OPENAI_API_KEY=$openaiKey

# === AI AGENT ===
DAILY_CAPITAL=$dailyCap
BASE_RISK_PERCENT=$baseRisk
ALPHA_MULTIPLIER=1.5
FEE_CAP=0.5

# === MEV BOT ===
JITO_API_KEY=$jitoKey
JITO_TIP_LAMPORTS=50000
MEV_MIN_SOL_SIZE=0.5
MEV_MAX_SLIPPAGE=10
MEV_ENABLED=false
MEV_MIN_SPREAD_PERCENT=2
MEV_TRADE_SIZE_SOL=0.1

# === CONFIG ===
WHITELIST_MODE=open
"@ | Out-File -FilePath ".env" -Encoding utf8

    Write-Host "  ✓ .env created" -ForegroundColor Green
}

Write-Host ""
Write-Host "Step 5/6: Database setup..." -ForegroundColor White
Write-Host ""

if (Test-Path "trades.json") {
    Write-Host "  ⚠ Found trades.json — migrating..." -ForegroundColor Yellow
    npm run migrate 2>$null
}

Write-Host "  ✓ Database ready" -ForegroundColor Green
Write-Host ""

Write-Host "Step 6/6: Building..." -ForegroundColor White
Write-Host ""

npx tsc --noEmit 2>$null
Write-Host "  ✓ TypeScript OK" -ForegroundColor Green
Write-Host ""

Write-Host "  ╔══════════════════════════════════════════════╗" -ForegroundColor Green
Write-Host "  ║                                              ║" -ForegroundColor Green
Write-Host "  ║      ✅ Setup Complete!                      ║" -ForegroundColor Green
Write-Host "  ║                                              ║" -ForegroundColor Green
Write-Host "  ╚══════════════════════════════════════════════╝" -ForegroundColor Green
Write-Host ""

Write-Host "  Quick Start:" -ForegroundColor White
Write-Host "    npm start" -ForegroundColor Cyan
Write-Host ""
Write-Host "  Production:" -ForegroundColor White
Write-Host "    npm run build" -ForegroundColor Cyan
Write-Host "    npm install -g pm2" -ForegroundColor Cyan
Write-Host "    pm2 start ecosystem.config.js" -ForegroundColor Cyan
Write-Host ""

$start = Read-Host "  Start bot now? (y/N)"
if ($start -eq "y" -or $start -eq "Y") {
    Write-Host ""
    npm start
}

